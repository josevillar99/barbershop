CREATE TABLE worker (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL UNIQUE REFERENCES app_user (id),
    active     BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE treatment_worker (
    treatment_id BIGINT NOT NULL REFERENCES treatment (id) ON DELETE CASCADE,
    worker_id    BIGINT NOT NULL REFERENCES worker (id) ON DELETE CASCADE,
    PRIMARY KEY (treatment_id, worker_id)
);

-- Las filas existentes se quedan con worker_id NULL: pasan a ser la "plantilla"
-- que se copia al crear cada trabajador nuevo. Ya no se editan directamente
-- (se retira el endpoint/pestana de horario global del salon).
ALTER TABLE business_hours ADD COLUMN worker_id BIGINT REFERENCES worker (id);
CREATE INDEX idx_business_hours_worker ON business_hours (worker_id);

ALTER TABLE appointment ADD COLUMN worker_id BIGINT REFERENCES worker (id);
CREATE INDEX idx_appointment_worker ON appointment (worker_id);

-- worker_id NULL en un bloqueo = bloqueo de todo el salon (asi se comportan
-- los bloqueos ya existentes, sin cambios).
ALTER TABLE schedule_block ADD COLUMN worker_id BIGINT REFERENCES worker (id);
CREATE INDEX idx_schedule_block_worker ON schedule_block (worker_id);

-- Permite invitar directamente como ADMIN (trabajador) en vez del flujo actual
-- de "se registra como USER y luego se asciende a mano".
ALTER TABLE signup_token ADD COLUMN role VARCHAR(20) NOT NULL DEFAULT 'USER';

-- Semilla: convierte la cuenta superadmin actual (si existe) en el primer
-- trabajador, con el horario que hoy tiene todo el salon como punto de partida
-- y capacidad para todos los servicios activos de hoy, para no dejar el sitio
-- sin huecos reservables justo despues de desplegar este cambio.
INSERT INTO worker (user_id, active)
SELECT id, TRUE FROM app_user WHERE role = 'SUPERADMIN'
ON CONFLICT (user_id) DO NOTHING;

INSERT INTO business_hours (day_of_week, start_time, end_time, worker_id)
SELECT bh.day_of_week, bh.start_time, bh.end_time, w.id
FROM business_hours bh
JOIN app_user u ON u.role = 'SUPERADMIN'
JOIN worker w ON w.user_id = u.id
WHERE bh.worker_id IS NULL;

INSERT INTO treatment_worker (treatment_id, worker_id)
SELECT t.id, w.id
FROM treatment t
JOIN app_user u ON u.role = 'SUPERADMIN'
JOIN worker w ON w.user_id = u.id
WHERE t.active = TRUE;
