-- Registro de auditoria: guarda el email del actor como texto plano (sin FK a app_user)
-- para que los logs sobrevivan intactos aunque se elimine el usuario mas tarde.
CREATE TABLE audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_email VARCHAR(255) NOT NULL,
    action      VARCHAR(50) NOT NULL,
    details     VARCHAR(500),
    created_at  TIMESTAMP NOT NULL DEFAULT now()
);

CREATE INDEX idx_audit_log_actor_email ON audit_log (actor_email);
CREATE INDEX idx_audit_log_action ON audit_log (action);
CREATE INDEX idx_audit_log_created_at ON audit_log (created_at DESC);
