CREATE TABLE app_user (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email      VARCHAR(255) NOT NULL,
    role       VARCHAR(20)  NOT NULL,
    created_at TIMESTAMPTZ  DEFAULT now() NOT NULL,
    CONSTRAINT uq_app_user_email UNIQUE (email)
);

CREATE TABLE login_code (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email      VARCHAR(255) NOT NULL,
    code_hash  VARCHAR(255) NOT NULL,
    expires_at TIMESTAMPTZ  NOT NULL,
    used       BOOLEAN      DEFAULT FALSE NOT NULL,
    created_at TIMESTAMPTZ  DEFAULT now() NOT NULL
);

CREATE INDEX idx_login_code_email ON login_code (email);

CREATE TABLE slot (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slot_date  DATE        NOT NULL,
    start_hour INTEGER     NOT NULL,
    status     VARCHAR(20) NOT NULL,
    booked_by  BIGINT      NULL,
    booked_at  TIMESTAMPTZ NULL,
    version    INTEGER     DEFAULT 0 NOT NULL,
    CONSTRAINT uq_slot_date_hour UNIQUE (slot_date, start_hour),
    CONSTRAINT fk_slot_booked_by FOREIGN KEY (booked_by) REFERENCES app_user (id),
    CONSTRAINT chk_slot_status CHECK (status IN ('AVAILABLE', 'BOOKED', 'DISABLED'))
);

CREATE INDEX idx_slot_date ON slot (slot_date);
CREATE INDEX idx_slot_booked_by ON slot (booked_by);
