DROP TABLE slot;

CREATE TABLE treatment (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name   VARCHAR(255) NOT NULL,
    active BOOLEAN      DEFAULT TRUE NOT NULL
);

CREATE TABLE treatment_segment (
    treatment_id  BIGINT      NOT NULL,
    segment_order INTEGER     NOT NULL,
    type          VARCHAR(20) NOT NULL,
    minutes       INTEGER     NOT NULL,
    CONSTRAINT pk_treatment_segment PRIMARY KEY (treatment_id, segment_order),
    CONSTRAINT fk_treatment_segment_treatment FOREIGN KEY (treatment_id) REFERENCES treatment (id) ON DELETE CASCADE,
    CONSTRAINT chk_treatment_segment_type CHECK (type IN ('WORK', 'WAIT'))
);

CREATE TABLE appointment (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appt_date      DATE         NOT NULL,
    start_time     INTEGER      NOT NULL,
    end_time       INTEGER      NOT NULL,
    treatment_id   BIGINT       NOT NULL,
    treatment_name VARCHAR(255) NOT NULL,
    status         VARCHAR(20)  NOT NULL,
    booked_by      BIGINT       NULL,
    booked_at      TIMESTAMPTZ  NULL,
    version        BIGINT       DEFAULT 0 NOT NULL,
    CONSTRAINT fk_appointment_booked_by FOREIGN KEY (booked_by) REFERENCES app_user (id),
    CONSTRAINT chk_appointment_status CHECK (status IN ('BOOKED', 'CANCELLED'))
);

CREATE INDEX idx_appointment_date ON appointment (appt_date);
CREATE INDEX idx_appointment_booked_by ON appointment (booked_by);

CREATE TABLE appointment_segment (
    appointment_id BIGINT      NOT NULL,
    segment_order  INTEGER     NOT NULL,
    type           VARCHAR(20) NOT NULL,
    minutes        INTEGER     NOT NULL,
    CONSTRAINT pk_appointment_segment PRIMARY KEY (appointment_id, segment_order),
    CONSTRAINT fk_appointment_segment_appt FOREIGN KEY (appointment_id) REFERENCES appointment (id) ON DELETE CASCADE,
    CONSTRAINT chk_appointment_segment_type CHECK (type IN ('WORK', 'WAIT'))
);

CREATE TABLE schedule_block (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    block_date DATE         NOT NULL,
    start_time INTEGER      NOT NULL,
    end_time   INTEGER      NOT NULL,
    reason     VARCHAR(500) NULL
);

CREATE INDEX idx_schedule_block_date ON schedule_block (block_date);

CREATE TABLE booking_lock (
    id BIGINT PRIMARY KEY
);

